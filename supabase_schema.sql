-- Run once in Supabase SQL Editor.
-- The public app may insert rows, but cannot read, update, or delete them.

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  session_id uuid not null,
  event_name text not null check (event_name in (
    'session_started', 'file_uploaded', 'qa_started', 'qa_completed',
    'qa_failed', 'report_downloaded', 'feedback_submitted'
  )),
  app_version text not null,
  event_data jsonb not null default '{}'::jsonb,
  constraint analytics_event_data_size check (octet_length(event_data::text) <= 10000),
  constraint analytics_no_sensitive_keys check (
    not (event_data ?| array['file_name', 'filename', 'source_text', 'target_text', 'email', 'glossary'])
  )
);

create table if not exists public.beta_feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  session_id uuid not null,
  satisfaction smallint not null check (satisfaction between 1 and 5),
  helpfulness text not null,
  false_positive_level text not null,
  most_useful_rule text,
  requested_features text check (char_length(requested_features) <= 1000),
  reuse_intent text not null,
  job_group text,
  comments text check (char_length(comments) <= 2000)
);

create table if not exists public.interview_opt_ins (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  session_id uuid not null,
  email text not null check (char_length(email) between 3 and 254)
);

alter table public.analytics_events enable row level security;
alter table public.beta_feedback enable row level security;
alter table public.interview_opt_ins enable row level security;

drop policy if exists "anonymous event insert" on public.analytics_events;
create policy "anonymous event insert" on public.analytics_events
  for insert to anon with check (true);

drop policy if exists "anonymous feedback insert" on public.beta_feedback;
create policy "anonymous feedback insert" on public.beta_feedback
  for insert to anon with check (true);

drop policy if exists "anonymous interview opt-in insert" on public.interview_opt_ins;
create policy "anonymous interview opt-in insert" on public.interview_opt_ins
  for insert to anon with check (true);

-- No SELECT/UPDATE/DELETE policy is created for anon. View data only from the
-- authenticated Supabase dashboard. Never place a service_role key in the app.

create index if not exists analytics_events_created_at_idx
  on public.analytics_events (created_at desc);
create index if not exists analytics_events_event_name_idx
  on public.analytics_events (event_name);
create index if not exists analytics_events_session_id_idx
  on public.analytics_events (session_id);
